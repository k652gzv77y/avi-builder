// Generates a themeable, typed icon set from the raw SVGs in public/icons.
//
// The raw files are Framer exports: 100x100, root `fill="none"`, with color
// applied via Framer token strings like
//   fill="var(--token-…, rgb(0,0,0)) /* {"name":"Icon BW"} */"
// and duotone `opacity="0.2"` layers. We normalise every color reference to
// `currentColor` so the icons inherit text color (and theme in light/dark),
// strip the outer <svg> wrapper, and emit a typed name -> inner-markup map.
//
// Run: node scripts/build-avi-icons.mjs

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import path from 'path';

const ICONS_DIR = path.join(process.cwd(), 'public/icons');
const OUT_DIR = path.join(process.cwd(), 'lib/avi-icons');
const OUT_FILE = path.join(OUT_DIR, 'generated.ts');

/** Turn a filename like "Align Left-1.svg" into a stable kebab-case id. */
function toIconName(fileName) {
  return fileName
    .replace(/\.svg$/i, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .toLowerCase()
    .replace(/^-+|-+$/g, '')
    .replace(/-1$/, '-alt');
}

/** Normalise a raw Framer SVG into inner markup that uses currentColor. */
function normalizeSvg(raw) {
  let s = raw.trim();
  // Drop the outer <svg …> … </svg> wrapper; we re-wrap at render time.
  s = s.replace(/^<svg[^>]*>/i, '').replace(/<\/svg>\s*$/i, '');
  // Replace Framer color-token fills/strokes with currentColor.
  s = s.replace(/(fill|stroke)="[^"]*--token[^"]*"/g, '$1="currentColor"');
  // Any remaining explicit black -> currentColor.
  s = s.replace(/(fill|stroke)="(#000000|#000|black|rgb\(0,\s*0,\s*0\))"/gi, '$1="currentColor"');
  // Collapse whitespace between tags to keep the generated file compact.
  return s.replace(/>\s+</g, '><').trim();
}

const files = readdirSync(ICONS_DIR).filter((f) => f.toLowerCase().endsWith('.svg'));
files.sort((a, b) => a.localeCompare(b));

const entries = [];
const seen = new Map();
for (const file of files) {
  const name = toIconName(file);
  if (seen.has(name)) {
    throw new Error(`Duplicate icon id "${name}" from "${file}" and "${seen.get(name)}"`);
  }
  seen.set(name, file);
  const body = normalizeSvg(readFileSync(path.join(ICONS_DIR, file), 'utf8'));
  entries.push({ name, body });
}

entries.sort((a, b) => a.name.localeCompare(b.name));

const names = entries.map((e) => e.name);
const union = names.map((n) => `  | '${n}'`).join('\n');
const map = entries
  .map((e) => `  '${e.name}': ${JSON.stringify(e.body)},`)
  .join('\n');

const out = `// AUTO-GENERATED by scripts/build-avi-icons.mjs — do not edit by hand.
// Source: public/icons/*.svg (Framer-exported set). Run \`npm run icons:build\`.
/* eslint-disable */

export type AviIconName =
${union};

/** Inner SVG markup for each icon, normalised to use \`currentColor\`. viewBox is 0 0 100 100. */
export const AVI_ICONS: Record<AviIconName, string> = {
${map}
};

export const AVI_ICON_NAMES: AviIconName[] = [
${names.map((n) => `  '${n}',`).join('\n')}
];
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, out, 'utf8');
console.log(`Generated ${entries.length} icons -> ${path.relative(process.cwd(), OUT_FILE)}`);
